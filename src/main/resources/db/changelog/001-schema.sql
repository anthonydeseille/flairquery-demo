--changeset flairquery:001-publisher
CREATE TABLE publisher (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    VARCHAR(255),
    country VARCHAR(64)
);

--changeset flairquery:001-author
CREATE TABLE author (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    birth_date DATE,
    bio        TEXT,
    ol_key     VARCHAR(32)
);

--changeset flairquery:001-book
CREATE TABLE book (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            VARCHAR(512) NOT NULL,
    isbn             VARCHAR(32),
    publication_year INTEGER,
    description      TEXT,
    author_id        BIGINT NOT NULL REFERENCES author (id),
    publisher_id     BIGINT REFERENCES publisher (id)
);
CREATE INDEX idx_book_author ON book (author_id);
CREATE INDEX idx_book_publisher ON book (publisher_id);

--changeset flairquery:001-review
-- TRAP 4 / TRAP 7: no index on reviewer_name nor created_at (on purpose, see demo-app/TRAPS.md)
CREATE TABLE review (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id       BIGINT NOT NULL REFERENCES book (id),
    rating        SMALLINT NOT NULL,
    reviewer_name VARCHAR(128),
    comment       TEXT,
    created_at    TIMESTAMP WITH TIME ZONE
);
CREATE INDEX idx_review_book ON review (book_id);
